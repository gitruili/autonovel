#!/usr/bin/env python3
"""
gen_characters.py -- 女频种田网文：角色注册表生成器（Foundation 阶段）。
读取 seed.txt + voice.md + world.md，调用大模型，输出 characters.md。
"""
import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from llm_client import call_text_model, default_model_for_role

BASE_DIR = Path(__file__).parent
load_dotenv(BASE_DIR / ".env")

WRITER_MODEL = os.environ.get(
    "AUTONOVEL_WRITER_MODEL",
    default_model_for_role("writer", "claude-sonnet-4-6"),
)

def call_writer(prompt, max_tokens=16000):
    return call_text_model(
        model=WRITER_MODEL,
        max_tokens=max_tokens,
        temperature=0.7,
        system=(
            "你是一位精通女频网文的角色设计师，擅长塑造接地气、有血有肉的人物。"
            "你深谙种田文角色的核心魅力：女主的坚韧与智慧、男主的闷骚与可靠、"
            "极品亲戚的可恨与可笑、配角的立体与可信。\n"
            "你设计的角色必须符合时代背景下的行为逻辑——"
            "一个古代农妇不会说出现代职场用语，一个村里的老太太不会像宫斗剧里的嫔妃。\n"
            "你创作的每个角色都有自己的利益诉求和说话习惯，"
            "去掉对话标签后读者也能分辨出是谁在说话。\n"
            "你从不使用 AI 废话词汇。你用简洁干练的文字写作。"
        ),
        messages=[{"role": "user", "content": prompt}],
        timeout=300,
    )

seed = (BASE_DIR / "seed.txt").read_text()
world = (BASE_DIR / "world.md").read_text()

# Voice Part 2 only
voice = (BASE_DIR / "voice.md").read_text()
voice_lines = voice.split('\n')
part2_start = next(i for i, l in enumerate(voice_lines) if 'Part 2' in l)
voice_part2 = '\n'.join(voice_lines[part2_start:])

prompt = f"""为这部女频种田网文构建一份完整的角色注册表（Character Registry）。
这是 CHARACTERS.MD —— 它是关于故事中每个人物的权威参考，
包括他们是谁、想要什么、怎么说话、藏着什么秘密。

种子概念 (SEED):
{seed}

生活设定集 (WORLD，这些角色生活的时代与社会):
{world}

文风标识 (VOICE，本小说的基调):
{voice_part2}

## 角色塑造要求

### 核心驱动力框架
每个主要角色都必须有清晰的驱动力链条：
  处境 (SITUATION) → 她/他最迫切想要什么？(WANT)
    → 她/他真正需要什么？(NEED，通常与 WANT 矛盾)
    → 她/他心底的错误信念是什么？(LIE，阻碍她/他的心结)
    → 她/他的弧光走向 (ARC，LIE 被打破或强化的过程)

规则：WANT 和 NEED 必须存在张力。
  比如女主 WANT 是"赚够钱离开这个破地方"，
  但 NEED 是"在这片土地上找到归属感和尊严"。

### 对话辨识度（6 个维度，适配种田文）
1. 用词习惯：文雅/粗俗/口头禅/地方俗语
2. 句子长短：碎嘴啰嗦型还是惜字如金型？
3. 说话语气：阴阳怪气/直来直去/绵里藏针/嘴硬心软
4. 口头禅/语言癖好：比如总爱说"我跟你说"、"哎呀你这人"
5. 隐喻来源：种田人用庄稼比喻、织女用布匹比喻、商人用银子比喻
6. 潜台词能力：话里有话还是有话直说？

测试：去掉"某某说"，读者是否仍能分辨出是谁在说话？

### 人物关系网（种田文核心）
种田文的戏剧张力大量来自人际关系。每个角色都必须：
- 与至少 2 个其他角色存在利益冲突或情感纠葛
- 有至少 1 个可能在故事中发生转变的关系（敌→友、友→敌、冷→暖等）

---

## 角色清单（根据种子概念动态生成）

请从种子概念中提取所有涉及的角色，并为每个角色构建完整档案。
通常一部种田文需要以下角色类型（根据种子概念调整具体人物）：

### 1. 女主（主角，视角人物）—— 最高优先级
必须包含：
- 基本信息：姓名、年龄、身份、外貌（具体，不用"美目流盼"这种废话）
- 穿越/重生前的身份与关键技能（如有）
- 驱动力链条：SITUATION → WANT → NEED → LIE → ARC
- 性格核心：她的底线是什么？她最怕什么？她最擅长什么？
- 说话方式（6 维度 + 3 句示例对话）
- 身体习惯和下意识小动作（比如思考时咬嘴唇、生气时攥拳头）
- 至少 2 个秘密（读者不会立刻知道的事）
- 金手指的使用习惯和心理（她怎么看待自己的优势？小心翼翼还是大胆使用？）

### 2. 男主 —— 高优先级
必须包含：
- 基本信息：姓名、年龄、身份、外貌
- 真实身份（如有隐藏身份）及隐瞒的原因
- 驱动力链条
- 他被女主吸引的具体原因（不是"她与众不同"这种废话，要具体到某个瞬间或特质）
- 说话方式（6 维度 + 3 句示例对话）
- 身体习惯（尤其是面对女主时的下意识反应）
- 至少 1 个秘密
- 他的短板/缺陷（不能是完美男人）

### 3. 核心对手（家庭内部）—— 高优先级
通常是极品亲戚、刻薄婆婆/婶娘、争产的兄弟等。
每个对手必须包含：
- 她/他为什么要刁难女主？（利益驱动，不是纯粹的坏）
- 她/他自己的处境和焦虑（让对手立体，不要脸谱化）
- 说话方式（尤其是"怎么阴阳怪气"和"怎么装好人"）
- 弱点（女主可以利用的突破口）
- 至少 1 句"名台词"（那种让读者恨得牙痒痒的话）

### 4. 外部势力对手 —— 中优先级
商业竞争者、地方恶霸、官府势力等。
每个必须包含：
- 他们的利益诉求和行事风格
- 与女主的利益冲突点
- 可合作/可对抗的灵活度

### 5. 助力型配角 —— 中优先级
帮助女主的人（但不能无条件帮忙，必须有自己的利益考量）。
可能包括：忠心的丫鬟/小厮、识货的掌柜、厚道的邻居等。
每个必须包含：
- 为什么帮女主（利益交换？报恩？被人格魅力折服？）
- 自己的小心思和局限性
- 说话方式

### 6. 氛围型配角 —— 低优先级
村里的八卦大婶、集市上的货郎、茶馆的闲汉等。
不需要完整档案，但需要：
- 1-2 句话概括人设
- 一个标志性的说话特征（让他们出场时读者能一秒认出来）

---

## 每个主要角色的输出模板

### [角色名]（[身份/定位]）

**基本信息**
- 姓名、年龄、身份
- 外貌速写（3-4 句，具体、有画面感，不用套话）

**驱动力链条**
- 处境 (SITUATION)：她/他目前的具体困境
- 欲望 (WANT)：她/他最想达到的外部目标
- 需求 (NEED)：她/他真正需要但不自知的东西
- 谎言 (LIE)：她/他心底的错误信念
- 弧光 (ARC)：从故事开头到结尾，这条信念链如何变化

**性格与行为**
- 性格核心（2-3 个关键词 + 解释）
- 底线/逆鳞（触碰了会爆发的点）
- 身体习惯/小动作（至少 2 个）

**说话方式**
- 6 维度描述
- 3 句示例对话（分别展示日常、生气、心软三种状态）
- 口头禅（如有）

**秘密**
- 至少 1 个读者不会立刻知道的事
- 这个秘密如果暴露，会怎么改变故事走向？

**关系网**
- 与每个相关角色的关系（用一句话概括）
- 哪些关系会在故事中发生转变？

**主题作用**
- 这个角色体现了故事的什么主题？

---

## 重要提示

- 角色必须互相咬合。一个角色的 WANT 应该与另一个角色的 WANT 冲突。
- 极品亲戚不能纯坏——她们有自己的焦虑和处境，只是处理方式令人发指。
- 男主不能是"霸总下凡"——他必须有自己的困境，且他的困境和女主的种田线有交集。
- 对话要有"时代感"——村妇不会说"赋能"，书生不会说"搞定"。
  但也不要写成文言文，要像人说话。
- 每个角色的秘密必须是那种"一旦暴露就会改变至少一条关系线"的级别。
- 目标字数约为 3000-4000 字。内容密集，严禁注水。
"""

print("正在生成角色注册表...", file=sys.stderr)
print(prompt)
result = call_writer(prompt)
print(result)

# save to file
with open(BASE_DIR / "characters.md", "w", encoding="utf-8") as f:
    f.write(result)
