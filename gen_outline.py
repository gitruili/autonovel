#!/usr/bin/env python3
"""
gen_outline.py -- 女频种田网文：章节大纲生成器（Foundation 阶段）。
读取 seed.txt + world.md + characters.md + MYSTERY.md + voice.md，
调用大模型，输出 outline.md。
"""
import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from llm_client import call_text_model, default_model_for_role

BASE_DIR = Path(__file__).parent
load_dotenv(BASE_DIR / ".env")

WRITER_MODEL = os.environ.get(
    "AUTONOVEL_WRITER_MODEL",
    default_model_for_role("writer", "claude-sonnet-4-6"),
)

def call_writer(prompt, max_tokens=16000):
    return call_text_model(
        model=WRITER_MODEL,
        max_tokens=max_tokens,
        temperature=0.5,
        system=(
            "你是一位精通女频种田网文的小说架构师。"
            "你深谙网文的章节节奏——开篇必须有钩子，每章结尾必须有悬念或期待感，"
            "种田升级线和情感线必须交替推进，打脸爽点必须有充分的铺垫。\n"
            "你熟悉种田文的经典结构：开局困境→初步立足→小有成就→遭遇打压→"
            "逆袭反击→事业高潮→感情明朗→大结局。\n"
            "你构建的大纲应当足以让作者直接撰写初稿，"
            "每一章都有明确的场景、情绪走向和推进目标，不需要临时编造剧情。\n"
            "你从不使用 AI 废话词汇。你用简洁干练的文字写作。"
        ),
        messages=[{"role": "user", "content": prompt}],
        timeout=600,
        include_beta=True,
    )

seed = (BASE_DIR / "seed.txt").read_text()
world = (BASE_DIR / "world.md").read_text()
characters = (BASE_DIR / "characters.md").read_text()

# MYSTERY.md（如果存在）
mystery_path = BASE_DIR / "MYSTERY.md"
mystery = mystery_path.read_text() if mystery_path.exists() else ""

# Voice Part 2 only
voice = (BASE_DIR / "voice.md").read_text()
voice_lines = voice.split('\n')
part2_start = next(i for i, l in enumerate(voice_lines) if 'Part 2' in l)
voice_part2 = '\n'.join(voice_lines[part2_start:])

prompt = f"""为这部女频种田网文构建一份完整的章节大纲。
目标：20-24 章，总字数约 8-10 万字（每章约 3,500-4,500 字）。

种子概念 (SEED):
{seed}

{"核心悬念 (MYSTERY，仅供架构师参考，读者将逐渐发现):" if mystery.strip() else ""}
{mystery}

生活设定集 (WORLD):
{world}

角色注册表 (CHARACTERS):
{characters}

文风标识 (VOICE):
{voice_part2}

---

## 大纲构建要求

### 整体结构（四幕式，适配种田文节奏）

请按以下结构规划全书：

**第一幕：开局困境（约 1-5 章，占全书 0-22%）**
- 建立女主的处境：穿越/重生后面对的具体困境
- 展示金手指的首次使用（但受限）
- 初步的人际冲突爆发（分家、被刁难、被看不起）
- 催化事件：迫使女主必须靠自己种田/经营谋生的转折点
- 男主的首次出场（自然，不刻意）

**第二幕上：初步立足（约 6-11 章，占全书 22-48%）**
- 种田线第一台阶→第二台阶的推进
- 女主凭本事赢得初步认可（但也招来嫉妒）
- 情感线破冰：从陌生/戒备到产生好感
- 第一次打脸（小爽点）：让看不起她的人吃瘪
- 中点反转（约 48%）：一个看似胜利但暗藏危机的节点

**第二幕下：遭遇打压（约 12-17 章，占全书 48-75%）**
- 女主事业做大，引来外部势力打压
- 家庭内部矛盾激化（秘密暴露、关系破裂）
- 情感线推进：并肩作战中感情升温
- 种田线第二台阶→第三台阶的推进
- 低谷时刻（约 70%）：女主遭遇最大危机，似乎要失去一切

**第三幕：逆袭与收获（约 18-24 章，占全书 75-100%）**
- 女主用智慧和积累反击，化危为机
- 大打脸（核心爽点）：让所有看不起她的人目瞪口呆
- 种田线达到第四台阶（事业巅峰）
- 情感线明朗化：感情确认
- 男主身份揭晓（如有隐藏身份）
- 大结局：展示女主改变命运后的新生活

---

### 逐章大纲格式

针对每一章，提供：

### 第 N 章: [标题]（标题要有网文感，能勾起好奇心）
- **核心推进:** 本章主要推进哪条线？（种田线 / 情感线 / 人际线 / 悬念线）
- **视角:** 女主第三人称有限视角
- **地点:** 具体的场景地点
- **% 进度:** 在全书中所处的位置
- **情绪走向:** 开头情绪 → 结尾情绪
- **关键场景:** 3-5 个必须发生的具体场景（用一句话描述每个场景）
- **种田进展:** 本章中女主的经营/产业有什么具体进展？（如本章无种田内容则写"无"）
- **情感进展:** 本章中女主与男主的关系有什么变化？（如本章无情感内容则写"无"）
- **人际变动:** 本章中人际关系发生了什么变化？谁的态度转变了？
- **伏笔植入:** 本章中埋下了什么线索？
- **伏笔回收:** 本章中回收了之前哪个伏笔？
- **章尾钩子:** 本章结尾留下什么悬念或期待感？（这是读者继续看下一章的理由）
- **爽点/虐点:** 本章是否有打脸、心动、委屈、感动等情绪爆发点？如有，用一句话描述
- **~目标字数:** 用于控制节奏

---

### 种田升级台账

一个跟踪女主产业发展的表格：
| 台阶 | 内容 | 起始章 | 完成章 | 标志性事件 | 经济变化 |

必须与 world.md 中的物价体系一致。

---

### 情感线进度台账

一个跟踪男女主感情发展的表格：
| 阶段 | 描述 | 章节范围 | 标志性名场面 |

至少包含 5 个阶段（如：无感→好奇→好感→心动→确认）。

---

### 伏笔台账

一个跟踪所有埋伏线索的表格：
| 线索 | 植入 (章) | 强化 (章) | 回收 (章) | 类型 |

至少包含 10 条线索。类型包括：实物、对话、行为、秘密、经济。
植入到回收之间必须至少间隔 3 章。

---

### 打脸/爽点台账

一个跟踪所有打脸和爽点场景的表格：
| 爽点 | 章节 | 被打脸的人 | 爽点描述 | 铺垫章节 |

至少包含 5 个爽点。每个爽点必须有至少 2 章的铺垫（先被欺负→后来翻盘）。

---

## 约束条件

1. **种田线不能断**：不能连续 3 章以上没有种田/经营内容的推进。
   种田线是读者追更的核心动力之一。

2. **情感线自然推进**：男女主不能一见钟情，必须有"日久生情"的过程。
   前 5 章只能有"初见"，不能有心动。

3. **经济逻辑自洽**：女主的每一笔收入和支出必须符合 world.md 中的物价体系。
   不能出现"卖了一方绣帕就买了一间铺面"的逻辑跳跃。

4. **打脸必须有铺垫**：每个打脸/逆袭场景之前，必须有至少 1-2 章的"被欺负"铺垫。
   先苦后甜才爽。

5. **章尾钩子必须有**：每一章的结尾都必须留下悬念或期待感。
   种田文读者是一章一章追的，没有钩子就弃文。

6. **节奏张弛有度**：不能连续 3 章以上都是高强度冲突。
   至少有 2-3 章是"温馨日常"——做饭、赶集、和邻居聊天、教徒弟织布。
   这些章节是种田文的"烟火气"担当，也是读者喘气的节点。

7. **季节和农时对应**：故事中的时间推进必须与 world.md 中的农作物周期、
   节日习俗对应。不能在冬天种水稻，不能在中元节开张。

8. **配角不是工具人**：极品亲戚每次出场都不能只是"来找麻烦"，
   她们也有自己的日子要过，偶尔也会展现人性的复杂一面。

9. **金手指使用有节制**：金手指不能每章都用，不能每次都完美解决问题。
   有时候女主必须靠自己的脑子和双手。

10. **目标字数约 3500-4500 字/章**：前 3 章可以略短（快速入戏），
    高潮章节可以略长，但单章不超过 5000 字。
"""

print("正在生成章节大纲...", file=sys.stderr)
result = call_writer(prompt)
print(result)

# save to file
with open(BASE_DIR / "outline.md", "w", encoding="utf-8") as f:
    f.write(result)
