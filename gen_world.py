#!/usr/bin/env python3
"""
gen_world.py -- 女频种田网文：生活设定集生成器（Foundation 阶段）。
读取 seed.txt + voice.md，调用大模型，输出 world.md（时代背景与社会经济设定）。
"""
import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from llm_client import call_text_model, default_model_for_role

BASE_DIR = Path(__file__).parent
load_dotenv(BASE_DIR / ".env")

WRITER_MODEL = os.environ.get(
    "AUTONOVEL_WRITER_MODEL",
    default_model_for_role("writer", "claude-sonnet-4-6"),
)

def call_writer(prompt, max_tokens=16000):
    return call_text_model(
        model=WRITER_MODEL,
        max_tokens=max_tokens,
        temperature=0.7,
        system=(
            "你是一位精通中国古代社会经济史的网文设定师，"
            "熟悉明清时期的农耕、商贸、礼法、民俗和日常生活。"
            "你构筑的设定集具有扎实的历史质感和浓郁的烟火气——"
            "读者能闻到灶头的柴火味，听到集市的叫卖声，摸到粗布衣裳的纹理。\n"
            "你的每一条设定都服务于叙事：物价体系让种田线有据可查，"
            "礼法规矩让人际冲突合情合理，地理物产让女主的发家路线自然可信。\n"
            "你从不编造脱离历史常识的设定。你用简洁、干练的文字写作，"
            "拒绝空洞的概述，只写具体的、可以直接用于写作的硬性细节。"
        ),
        messages=[{"role": "user", "content": prompt}],
        timeout=300,
    )

seed = (BASE_DIR / "seed.txt").read_text()
voice = (BASE_DIR / "voice.md").read_text()

# Extract voice Part 2 only (the novel-specific voice)
voice_lines = voice.split('\n')
part2_start = next(i for i, l in enumerate(voice_lines) if 'Part 2' in l)
voice_part2 = '\n'.join(voice_lines[part2_start:])

prompt = f"""为这部女频种田网文构建一份完整的生活设定集。这是 WORLD.MD 文件——
它是这个故事发生的时代背景、社会规则和经济体系的权威参考。
作者写任何一个场景时，都应当能从此文档中找到所需的硬性细节，
不需要临时编造"一斗米多少钱""女人能不能开铺子"这类问题的答案。

种子概念 (SEED):
{seed}

语气标识 (VOICE，此小说的基调):
{voice_part2}

创作要求:
- 所有设定必须服务于"种田线"和"人际线"的推进
- 经济数据必须自洽（收入与支出对得上，升级台阶在经济上合理）
- 礼法规矩必须既能制造冲突、又能被女主用智慧突破
- 地理物产必须能解释女主"为什么能在这里发家"
- 每一条设定都要具体到可以直接用于写作的程度
- 冰山原则：暗示的内容多于直接陈述的内容

请按以下章节组织文档：

## 时代背景
故事发生在什么朝代（或架空哪个朝代）？当前的政治大环境是什么？
是太平盛世还是乱世初定？最近发生了什么影响底层百姓生活的大事
（比如战乱刚结束、新帝登基减税、旱灾蝗灾、开放海禁等）？
这些大背景如何影响故事中人物的处境和机遇？

## 经济体系
### 货币与物价
当地通用货币体系（铜板、银两、银票的换算关系）。
列出核心物价清单（必须覆盖以下品类，每项给出具体数字）：
  - 粮食类：一斗米、一斗面、一斤猪肉、一只鸡
  - 日用类：一匹粗布、一匹细布、一斤盐、一斤油、一壶酒
  - 住房类：村里一间泥砖房、镇上一间铺面的租金/购价
  - 劳力类：短工日工钱、长工月工钱、丫鬟/小厮的身价
  - 特殊品类：与种子概念中女主经营方向相关的原材料和成品价格

### 税赋与徭役
田赋怎么交（按亩？按产？）、商税怎么收、有没有摊丁入亩？
女户/寡妇有没有减免政策？开铺子需要什么手续？
走商需要什么路引/文书？

### 商业环境
当地的集市怎么运作（几日一集？在哪里？）。
商铺的规矩（租赁 vs 自购、牙行怎么运作）。
长途贸易的路线和成本（水路 vs 陆路、镖局/商队）。
有没有商会/行会？对女性经商有什么限制或惯例？

## 社会阶层与礼法
### 阶层结构
当地的社会分层（地主乡绅→自耕农→佃户→流民）。
各阶层的标志性差异（住什么房、穿什么衣、吃什么饭、嫁娶排场）。

### 婚姻与家族
婚嫁礼法（聘礼、嫁妆的一般标准）。
休妻/和离的法律与社会后果。
分家的规矩（嫡庶、长幼、已婚未婚的分配惯例）。
寡妇再嫁的社会观感。女子的财产权（嫁妆归谁？私房钱？）。
立女户的条件和社会代价。

### 女性地位
女性在不同阶层中的实际处境（底层农妇 vs 商户娘子 vs 乡绅夫人）。
女性可以做哪些营生（不违反礼法的）？哪些营生会被人说闲话？
女性出门抛头露面的尺度（乡下 vs 镇上 vs 府城的差异）。

### 官府与法律
县衙的基本运作（县令、师爷、衙役、里正/保长）。
打官司的流程和成本。民间纠纷的常见解决方式。
对种田线和人际线有影响的具体律法条文。

## 地理与物产
### 核心地点
女主所在村落的具体描写：地形、气候、土壤、水源、距离最近的镇/县城多远。
村落的规模（多少户？）、布局、邻里关系的空间特征。
镇上/县城的布局：主街、集市、码头/渡口、衙门、学堂的位置关系。

### 物产与资源
当地的主要农作物和种植周期（什么季节种什么、几月收获）。
可利用的野生资源（山上有什么？水里有什么？林子里有什么？）。
当地的特色物产或手工艺传统（与女主的种田线呼应）。
周边府城或其他地区对什么商品有需求（贸易机会）？

### 感官特征
为每个关键地点写出感官速写（看到什么、听到什么、闻到什么）。
不同季节的氛围变化。

## 民俗与日常生活
### 饮食
当地人一日几餐？主食是什么？常见的菜式？
待客的规矩（来人了必须端什么？不能端什么？）。
与女主经营方向相关的饮食文化细节。

### 服饰与住房
不同阶层的穿着差异（从补丁麻衣到绫罗绸缎）。
农家小院的典型布局（几间房、灶房在哪、院子多大、有没有菜园）。
镇上铺面的典型格局（前店后家？几开间？）。

### 节气与习俗
一年中的重要节日和对应习俗（可用于情节推进的节点）。
婚丧嫁娶的流程和忌讳。
邻里之间的人情往来规矩（送礼、帮工、红白事）。

### 医疗与卫生
生病了怎么看？村里有没有郎中？看一次病大概多少钱？
常见的偏方和土法。产妇/幼儿的护理习惯。
（如果女主有医术金手指，这部分需要更详细。）

## 关键 NPC 与势力（非主角团）
当地有影响力的人物（里正、乡绅、大商户、学堂先生等）。
他们各自的利益诉求和彼此的关系网。
哪些人可能成为女主的助力？哪些人可能成为阻碍？

## 内部一致性规则（作者不可违反）
列出 10-15 条硬性约束，比如：
  - 物价波动不超过 ±20%（除非有剧情事件如天灾导致）
  - 女主的金手指不能突破设定的局限性
  - 分家后女主不能再使用原家庭的资源
  - 季节、农时必须与实际对应（不能冬天种水稻）
  - 社会规矩的突破必须有代价（不能毫无阻力地颠覆礼法）
  - 等等……根据种子概念补充更多

重要提示 (IMPORTANT):
- 务必具体。不要说"物价适中"，要给出具体数字。
  不要说"当地盛产农作物"，要说出是什么作物、什么季节、亩产多少。
- 所有经济数据必须内部自洽：女主一天摆摊能赚多少钱？
  够不够买一斤肉？攒多久能租个铺面？这些数字必须对得上。
- 礼法规矩既要制造压力（让女主面临困境），
  又要留有缝隙（让女主能用智慧找到突破口）。
- 用简洁、干练的散文体写作。严禁AI废话。
  不要用"丰富多彩""博大精深""源远流长"这类空话。
- 目标字数约为 3000-4000 字。内容密集，严禁注水。
  每一条设定都必须是作者写正文时"查得到、用得上"的硬性细节。
"""

print("正在生成生活设定集...", file=sys.stderr)
print(prompt)
result = call_writer(prompt)
print(result)

# save to file
with open(BASE_DIR / "world.md", "w", encoding="utf-8") as f:
    f.write(result)
