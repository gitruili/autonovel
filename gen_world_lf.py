#!/usr/bin/env python3
"""
gen_world_lf.py -- 长篇女频种田网文：生活设定集生成器（Foundation 阶段）。
读取 seed.txt + voice.md，调用大模型，输出 world.md。
Part A: 核心设定（V1-3 范围，~3000词）
Part B: 扩展路线图（~2000词）
"""
import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from llm_client import call_text_model, default_model_for_role

BASE_DIR = Path(__file__).parent
load_dotenv(BASE_DIR / ".env")

WRITER_MODEL = os.environ.get(
    "AUTONOVEL_WRITER_MODEL",
    default_model_for_role("writer", "claude-sonnet-4-6"),
)

def call_writer(prompt, max_tokens=16000):
    return call_text_model(
        model=WRITER_MODEL,
        max_tokens=max_tokens,
        temperature=0.7,
        system=(
            "你是一位精通中国古代社会经济史的网文设定师，"
            "熟悉明清时期的农耕、商贸、礼法、民俗和日常生活。"
            "你构筑的设定集具有扎实的历史质感和浓郁的烟火气——"
            "读者能闻到灶头的柴火味，听到集市的叫卖声，摸到粗布衣裳的纹理。\n"
            "你精通百万字长篇网文的世界观架构，擅长设计可扩展的世界设定——"
            "每一个设定模块都预留了「升级接口」，随着故事推进，世界可以自然地扩展和深化。\n"
            "你的每一条设定都服务于叙事：物价体系让种田线有据可查，"
            "礼法规矩让人际冲突合情合理，地理物产让女主的发家路线自然可信。\n"
            "你从不编造脱离历史常识的设定。你用简洁、干练的文字写作，"
            "拒绝空洞的概述，只写具体的、可以直接用于写作的硬性细节。"
        ),
        messages=[{"role": "user", "content": prompt}],
        timeout=600,
    )

seed = (BASE_DIR / "seed.txt").read_text()
voice = (BASE_DIR / "voice.md").read_text()

# Extract voice Part 2 only
voice_lines = voice.split('\n')
part2_start = next(i for i, l in enumerate(voice_lines) if 'Part 2' in l)
voice_part2 = '\n'.join(voice_lines[part2_start:])

prompt = f"""为这部**百万字长篇**女频种田网文构建一份完整的生活设定集。
这份文档分两部分：Part A 是核心设定（卷1-3 立即需要的），Part B 是扩展路线图（后续卷需要的）。

种子概念 (SEED):
{seed}

语气标识 (VOICE):
{voice_part2}

---

# Part A: 核心设定（卷1-3 范围）

这是故事开始时立即需要的详细设定。作者写前60章时，都应当能从此部分找到所需的硬性细节。

请按以下章节组织：

## 时代背景
故事发生在什么朝代（或架空哪个朝代）？当前的政治大环境？
最近发生了什么影响底层百姓生活的大事？这些大背景如何影响人物的处境和机遇？

## 经济体系
### 货币与物价
当地通用货币体系。列出核心物价清单（必须覆盖，每项给出具体数字）：
  - 粮食类：一斗米、一斗面、一斤猪肉、一只鸡
  - 日用类：一匹粗布、一匹细布、一斤盐、一斤油、一壶酒
  - 住房类：村里一间泥砖房、镇上一间铺面的租金/购价
  - 劳力类：短工日工钱、长工月工钱、丫鬟身价
  - 特殊品类：与女主经营方向相关的原材料和成品价格

### 税赋与徭役
田赋、商税、女户政策、开铺手续、走商文书。

### 商业环境
集市运作、商铺规矩、长途贸易、行会、对女性经商的限制。

## 社会阶层与礼法
### 阶层结构
当地社会分层及各阶层的标志性差异。

### 婚姻与家族
婚嫁礼法、休妻/和离、分家规矩、寡妇再嫁、女子财产权、立女户。

### 女性地位
女性在不同阶层的实际处境、可做的营生、抛头露面的尺度。

### 官府与法律
县衙运作、打官司流程、对种田线和人际线有影响的具体律法。

## 地理与物产
### 核心地点
女主所在村落/寨子的具体描写：地形、气候、土壤、水源、距离最近的镇/县城多远。
村落规模、布局。镇上/县城的布局。

### 物产与资源
主要农作物和种植周期。野生资源。特色物产。贸易需求。

### 感官特征
每个关键地点的感官速写。不同季节的氛围变化。

## 民俗与日常生活
### 饮食
一日几餐、主食、常见菜式、待客规矩。

### 服饰与住房
不同阶层穿着差异。农家小院布局。铺面格局。

### 节气与习俗
重要节日、婚丧嫁娶、邻里人情往来。

### 医疗与卫生
看病方式、费用、偏方、产妇护理。

## 关键 NPC 与势力
当地有影响力的人物及其利益诉求、关系网。

## 内部一致性规则（作者不可违反）
10-15 条硬性约束（物价稳定性、金手指局限、季节农时、社会规矩代价等）。

---

# Part B: 扩展路线图（卷4+ 的世界扩展规划）

这是百万字长篇独有的部分。随着女主从村镇走向县城、府城、京城，世界必须同步扩展。
每一个扩展锚点都要具体到可以直接用于写作的程度。

请按以下结构组织：

## 地理扩展锚点
定义 4-6 个后续会解锁的地点，每个标注"解锁卷号"：
  - 地点名称
  - 解锁卷号（大约在第几卷登场）
  - 与初始地点的距离和交通方式
  - 该地点的核心特征（规模、人口、经济水平、权力结构）
  - 该地点独有的物价体系或商业规则
  - 女主为什么需要去这里（剧情驱动力）

## 经济层级扩展
定义 3-4 个经济层级，每个层级对应新的挑战：
  - 层级名称（如：村级小贩 → 镇级商户 → 县级行商 → 府城大贾）
  - 对应卷号范围
  - 日/月/年收入量级
  - 新出现的经济工具（如：从铜钱到银两到银票）
  - 新出现的商业规则（如：从摆摊到租铺到开行会到跨省贸易）
  - 每个层级升级时的核心瓶颈是什么

## 势力扩展锚点
定义后续卷会登场的新势力：
  - 势力名称
  - 登场卷号
  - 势力类型（商会、官府、军队、朝堂、外敌等）
  - 与女主的关系（潜在助力/阻碍/中立）
  - 该势力的核心诉求
  - 女主与该势力的博弈方式

## 世界观伏笔锚点
3-5 条世界级别的悬念，从卷1埋下、后续卷才揭示：
  - 伏笔内容
  - 埋设方式（自然融入日常描写，不能刻意）
  - 揭示卷号
  - 揭示后对剧情的影响

---

重要提示 (IMPORTANT):
- Part A 的详细度与短篇 world.md 完全一致——具体数字、具体规则、可直接用于写作
- Part B 的每个锚点也要具体——不能只说"后续会去府城"，要给出府城的名字、规模、物价差异
- 所有经济数据必须内部自洽
- 用简洁、干练的散文体写作。严禁AI废话
- Part A 目标 ~3000 字，Part B 目标 ~2000 字，总计 ~5000 字
- 两部分之间用明确的分隔线隔开
"""

print("正在生成长篇生活设定集...", file=sys.stderr)
result = call_writer(prompt)
print(result)

# save to file
with open(BASE_DIR / "world.md", "w", encoding="utf-8") as f:
    f.write(result)

print(f"\n已保存到 world.md ({len(result)} 字符)", file=sys.stderr)
