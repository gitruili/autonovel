import argparse
import json
import os
import sys
from pathlib import Path
from dotenv import load_dotenv
from llm_client import (
    call_text_model,
    default_model_for_role,
    get_api_key,
    provider_api_key_env,
)

BASE_DIR = Path(__file__).parent
load_dotenv(BASE_DIR / ".env")

from story_schema import load_project_tags

WRITER_MODEL = os.environ.get(
    "AUTONOVEL_WRITER_MODEL",
    default_model_for_role("writer", "claude-sonnet-4-6-20250217"),
)


def call_writer(prompt, max_tokens=8192):
    return call_text_model(
        model=WRITER_MODEL,
        max_tokens=max_tokens,
        temperature=1.0,
        system=(
            "你是一名专业女频网文作者，精通晋江文学城、番茄小说网、七猫小说网种田文的创作技巧和热点元素。"
            "你熟读该领域的经典与热门作品——"
            "如关心则乱《知否知否应是绿肥红瘦》（宅斗+经营的典范）、"
            "希行《娇娘医经》（女主凭本事立足的标杆）、"
            "闲听落花《锦心似玉》（家宅经营与人情世故）、"
            "意千重《田韵》（扎实的古代农耕生活流）、"
            "郁雨竹《随身带着一口泉》（金手指与种田结合的经典）、"
            "以及《农门婆婆的诰命之路》《娘子万安》等热门种田文。\n"
            "你具备极强的洞察力和发散思考能力，擅长综合各种信息关联思考，"
            "分析出不同寻常的发展机遇，准确推演各种事件的影响与发展。\n"
            "你深谙种田文的核心魅力：从一穷二白到家业兴旺的成长爽感、细腻真实的古代/乡村生活细节、"
            "接地气的人情冷暖与家长里短、女主凭智慧和勤劳改变命运的独立精神。\n"
            "你生成的构思必须是**具体的、令人惊喜的、结构稳健的**。"
            "永远不要提议'穿越古代+空间+种田+男主是王爷'这种烂大街的模板。"
            "每个概念都应该让读者心想：'这个设定我没见过，这个女主的日子我想跟着过下去。'\n"
            "你的回答总是直截了当，直接输出最终回答，不输出任何说明性的内容。"
        ),
        messages=[{"role": "user", "content": prompt}],
        timeout=720,
        include_beta=True,
    )


# ──────────────────────────────────────────────────────────────
#  种田文定义（供 Prompt 引用）
# ──────────────────────────────────────────────────────────────
GENRE_DEFINITION = """
## 种田文定义
主角利用知识（现代知识、特殊技能、空间金手指等）或勤劳智慧，从低起点开始，
一步一个脚印地积累财富、改善生活、提升地位、影响环境。
- 核心：建设与发展，如开荒、建房、畜牧、养殖、制作工具、改善生活、发展手工业、
  经营领地、发展村落/城镇、经商致富、推广技术等（不必同时包含所有）
- 看点：亲近自然、猎奇、积累感与获得感、知识/技能应用、建设成就感、
  温馨的人际关系、日久生情的感情线
- 初始：艰苦的环境、一无所有
- 过程：从无到有、注重技术与智慧、展现积累与变化
"""

# ──────────────────────────────────────────────────────────────
#  书名设计规范
# ──────────────────────────────────────────────────────────────
TITLE_RULES = """
## 书名设计原则
1. 精准定位：通过核心关键词告诉读者"这是什么类型的故事"
2. 瞬间引爆：通过强烈的冲突、情绪词或反差制造"这故事看起来很带劲！"的感觉
3. 清晰传达：点明女主的核心状态、目标或金手指
4. 简洁有力：8-15字，信息密度高
5. 符号点睛：合理使用符号增强节奏感和视觉冲击力

书名公式参考：
- 【状态/事件】+【身份】+【金手指/反转结果】+【情绪词】
  例：《被休弃后，农妇她带着空间杀疯了》
- 【金手指/身份】+【事件/状态】+【反转/结果】
  例：《随身带个小药园，我在古代当首富》
- 【核心冲突/悬念】+【身份/关系】
  例：《分家后，我靠种田打脸全村》
  例：《逃荒路上捡了个将军老公》
"""

# ──────────────────────────────────────────────────────────────
#  简介设计规范
# ──────────────────────────────────────────────────────────────
SYNOPSIS_RULES = """
## 简介设计原则
高点击率简介 = 炸裂开头（钩子）+ 明确标签 + 核心爽点 + 极致情绪 + 简洁节奏

1. 黄金前三句（核心钩子）：
  - 强烈冲突/反转："睁眼就被泼了一盆冷水赶出家门，婆婆笑她活不过冬天。三年后，她的铺子开遍整条街。"
  - 极端困境："穿成农门弃妇，兜里三文钱，身边一个病秧子小叔和两个饿哭的娃。"
  - 炸裂信息/悬念："分家只分到三亩荒地一间破屋，她笑着接了——没人知道她随身带着一个灵泉空间。"

2. 明确核心标签：
  - 直接点明：【穿越+种田+空间+美食+甜宠】
  - 女频种田热门标签参考：发家致富/种田经商、穿越架空、重生宅斗、
    美食经营、空间灵泉、医术/药膳、二嫁/寡妇逆袭、逃荒基建、
    锦鲤福宝、团宠、先婚后爱、日久生情、打脸虐渣

3. 突出种田升级线和金手指：
  - 展示从无到有的成长路径和核心爽点
  - 点明金手指如何帮助女主破局

4. 强烈的情绪驱动：
  - 打脸预期："当初嫌她穷酸的妯娌，如今求着她帮忙。"
  - 甜点暗示："那个替她挡风遮雨的沉默男人，红着耳尖问她：'娘子……今晚能喝你煮的汤吗？'"
  - 关键：让读者看完简介就感到"好爽！好甜！好想追下去！"

5. 简洁有力：不超过3-4段，多用短句、感叹句，像短视频文案一样"短、平、快、爆"

6. 结尾悬念："这一世，她要让所有看不起她的人，排着队喊她一声'东家娘子'！"
"""

# ──────────────────────────────────────────────────────────────
#  生成提示词（主模板）
# ──────────────────────────────────────────────────────────────
GENERATE_PROMPT = """生成 {count} 个女频种田网文的种子概念。每一个都应该是
一个完整的前提，足以支撑起一整部中篇网文（约 8-10 万字，20-24 章）的构建。

{tags_context}

{genre_definition}

{title_rules}

{synopsis_rules}

## 每个概念必须包含以下要素

### 开局困境
女主一开始面临的具体困境是什么？要有画面感和紧迫感。
好例子："醒来发现自己是个被婆家赶出来的弃妇，身边一个病秧子小叔子，兜里三文钱，外面还下着雪。"
坏例子："穿越到古代生活很艰难。"（太笼统）

### 时代/地点
具体的时代背景和生活环境。不要只说"古代"，要明确到什么样的村镇、
什么气候、什么物产、周边有什么地理特征（靠山？临水？边关？盐场？茶山？渔村？）。
体现出"这个地方"独有的生存规则和发展机会。

### 金手指
女主的核心优势是什么？可以是：
  - 现代知识技能（医术、厨艺、农技、经商头脑、手工艺等）
  - 随身空间/灵泉/系统（但必须有明确限制和升级条件）
  - 前世记忆（重生文）
  - 或者纯粹靠智商和性格（无金手指硬核种田）
关键：金手指必须有局限性（比如空间一天只能进去一次、灵泉水量有限、
系统任务有时限等），不能让女主无所不能，否则没有戏剧张力。

### 种田线
女主的核心经营/发家路线是什么？要具体到产业，并且设计出3-4个升级台阶。
好例子："利用现代腌制技术做酱菜→摆摊攒钱→开铺子→建作坊供应府城大酒楼→成为一方商户"
坏例子："种地赚钱。"（太笼统）
种田线是故事的骨架，每个台阶都应该对应一个爽点爆发和新的挑战。

### 人际困局
女主面临的人际关系核心矛盾是什么？
  - 家庭内部：极品亲戚、刻薄婆婆/继母、争家产、分家、立户等
  - 外部势力：恶霸乡绅、商业竞争对手、官府压迫等
  人际线和种田线必须互相咬合——比如经营做大了反而招来嫉妒和打压。

### 情感线
男主是谁？他的人设亮点是什么？他和女主的感情发展逻辑是什么？
男主不能是完美霸总，必须有自己的困境或缺陷（穷、伤残、被家族放逐、身份隐瞒等）。
感情线要有"日久生情"的真实感——从互相防备/无感到并肩作战到心动。
要设计至少一个"名场面"（让读者截图分享的心动瞬间）。

### 主题
这个故事的精神内核是什么？
好例子："一个人到底是被出身定义，还是被自己的选择定义？"
坏例子："努力就会成功。"（太说教）

## 多样性要求
确保这 {count} 个概念具有多样性：
  - 至少有一个纯种田经营流（重心在产业发展，感情线为辅）
  - 至少有一个家宅/宅斗流（重心在家族内部的人情博弈）
  - 至少有一个有轻微奇幻元素的（空间/系统/异能，但主体仍是种田）
  - 至少有一个硬核无金手指的（纯靠智商、技能和人脉翻身）
  - 至少有一个非典型古代背景的（比如边关、海边渔村、少数民族聚居区、乱世逃荒）
  - 混合不同基调：温馨治愈、逆袭打脸、细水长流、先苦后甜

## 禁止生成
  - 女主一穿越就被王爷/世子看上的"霸总"套路
  - 金手指没有任何限制、女主无所不能的"躺赢"设定
  - 男主替女主解决所有问题、女主只负责"美"的花瓶设定
  - 所有配角都是坏人/所有好人都帮女主的黑白脸谱化
  - 宫斗为主线的（我们要的是种田，不是后宫争宠）
  - 纯虐文或BE结局（种田文的核心是"生活越来越好"的希望感）
  - 如果是现实题材，请勿加入过多超现实元素和浮夸的设计，紧扣现实逻辑

## 输出模板（严格按此格式）

# 创意<序号>：《<书名>》

## 作品简介
<按照简介设计原则撰写，标签放在最前面，3-4段，短句为主，情绪炸裂>

## 核心卖点
<一句话描述核心卖点/核心梗：女主走上怎样的发家之路？最大的爽点是什么？>

## 开局困境
<具体的、有画面感的起始困境>

## 金手指与局限
<金手指是什么？局限性是什么？升级条件是什么？>

## 种田升级线
<3-4个升级台阶，每个台阶对应的产业、爽点和挑战>

## 人际困局
<家庭内部矛盾 + 外部势力矛盾>

## 情感线
<男主人设 + 感情发展逻辑 + 至少一个名场面设计>

## 时代/地点
<具体的时代背景、地理环境、物产特色>

## 主题
<一句话精神内核>
"""

# ──────────────────────────────────────────────────────────────
#  扩展提示词（基于已有想法变体）
# ──────────────────────────────────────────────────────────────
RIFF_PROMPT = """我有一个女频种田网文的种子构思：

"{idea}"

{tags_context}

{genre_definition}

{title_rules}

{synopsis_rules}

基于这个概念生成 5 个变体。保留核心构思中吸引人的部分，但将其推向不同的方向。

确保这些变体之间有真正的区别——不要只是微调表面细节。
可以改变的维度包括：时代背景、金手指类型、种田产业方向、男主人设、
家庭关系结构、故事基调（温馨 vs 爽文 vs 细水长流）。

按以下模板输出每个变体：

# 创意<序号>：《<书名>》

## 不同之处
<从原始种子中改变了什么，为什么要改变？>

## 作品简介
<按照简介设计原则撰写，标签放在最前面，3-4段，短句为主，情绪炸裂>

## 核心卖点
<一句话核心卖点>

## 开局困境
<具体困境>

## 金手指与局限
<金手指 + 局限性>

## 种田升级线
<3-4个升级台阶>

## 人际困局
<家庭 + 外部>

## 情感线
<男主人设 + 感情逻辑 + 名场面>

## 时代/地点
<具体背景>

## 爽点设计
<最让读者拍案叫绝的"逆袭"时刻>
"""


def main():
    parser = argparse.ArgumentParser(description="生成女频种田网文种子构思")
    parser.add_argument("--count", type=int, default=3,
                        help="生成的构思数量 (默认: 3)")
    parser.add_argument("--riff", type=str, default=None,
                        help="基于现有想法进行扩展")
    args = parser.parse_args()

    if not get_api_key():
        print(f"ERROR: Set {provider_api_key_env()} in .env first")
        sys.exit(1)

    _, tags_context = load_project_tags()

    if args.riff:
        print(f"正在基于以下想法扩展: {args.riff}\n")
        prompt = RIFF_PROMPT.format(
            idea=args.riff,
            tags_context=tags_context,
            genre_definition=GENRE_DEFINITION,
            title_rules=TITLE_RULES,
            synopsis_rules=SYNOPSIS_RULES,
        )
    else:
        print(f"正在生成 {args.count} 个种田网文种子构思...\n")
        prompt = GENERATE_PROMPT.format(
            count=args.count,
            tags_context=tags_context,
            genre_definition=GENRE_DEFINITION,
            title_rules=TITLE_RULES,
            synopsis_rules=SYNOPSIS_RULES,
        )

    print(prompt)
    print("-----------------")
    result = call_writer(prompt, max_tokens=8192)
    print(result)
    print("\n" + "=" * 60)
    print("要挑选一个种子，请将你喜欢的概念复制到 seed.txt 中：")
    print("  nano seed.txt")
    print("或者将几个概念重新组合成你自己的种子。")
    print("然后继续 WORKFLOW.md 中的第 2 步。")


if __name__ == "__main__":
    main()
